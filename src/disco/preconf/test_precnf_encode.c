static void
check_bytes( char const *  name,
             uchar const * got,
             ulong         got_sz,
             uchar const * exp,
             ulong         exp_sz ) {
  if( FD_UNLIKELY( got_sz!=exp_sz || memcmp( got, exp, exp_sz ) ) ) {
    FD_LOG_HEXDUMP_WARNING(( "got", got, got_sz ));
    FD_LOG_HEXDUMP_WARNING(( "expected", exp, exp_sz ));
    FD_LOG_ERR(( "%s: encoding mismatch (got %lu bytes, expected %lu)", name, got_sz, exp_sz ));
  }
}

static uint
ip4( uchar a, uchar b, uchar c, uchar d ) {
  uchar bytes[4] = { a, b, c, d };
  uint  v;
  memcpy( &v, bytes, 4UL );
  return v; /* network byte order, as in fd_txn_m_t.source_ipv4 */
}

static uchar             buf[ FD_PRECNF_BATCH_ENC_MAX ];
static fd_precnf_batch_t batch[1];

/* Encodes the batch and checks that fd_precnf_batch_encoded_sz agrees
   with the bytes actually written. */
static ulong
encode( long ts ) {
  ulong exp_sz = fd_precnf_batch_encoded_sz( batch, ts );
  ulong sz     = fd_precnf_batch_encode( batch, ts, buf, sizeof(buf) );
  FD_TEST( sz && sz==exp_sz );
  return sz;
}

static void
test_heartbeat( void ) {
  uchar out[ FD_PRECNF_HEARTBEAT_ENC_MAX ];
  check_bytes( "hb0",   out, fd_precnf_encode_heartbeat( out,   0UL ), hb0,   sizeof(hb0)   );
  check_bytes( "hb5",   out, fd_precnf_encode_heartbeat( out,   5UL ), hb5,   sizeof(hb5)   );
  check_bytes( "hb300", out, fd_precnf_encode_heartbeat( out, 300UL ), hb300, sizeof(hb300) );
  FD_TEST( fd_precnf_encode_heartbeat( out, ULONG_MAX )<=FD_PRECNF_HEARTBEAT_ENC_MAX );
}

static void
test_batch_reference( void ) {
  uchar p1[ 200 ]; for( ulong i=0UL; i<200UL; i++ ) p1[ i ] = (uchar)i;
  uchar p2[ 150 ]; for( ulong i=0UL; i<150UL; i++ ) p2[ i ] = (uchar)( i*7UL );

  /* One packet with an address and a timestamp that has nanos. */
  fd_precnf_batch_init( batch );
  FD_TEST( fd_precnf_batch_append( batch, p1, sizeof(p1), ip4( 10, 0, 0, 1 ) ) );
  check_bytes( "batch1", buf, encode( 1700000000123456789L ), batch1, sizeof(batch1) );

  /* Two packets, the second without an address (BAM), and a whole-second
     timestamp so Timestamp.nanos is omitted. */
  fd_precnf_batch_init( batch );
  FD_TEST( fd_precnf_batch_append( batch, p1, sizeof(p1), ip4( 192, 168, 255, 7 ) ) );
  FD_TEST( fd_precnf_batch_append( batch, p2, sizeof(p2), 0U ) );
  FD_TEST( fd_precnf_batch_txn_cnt( batch )==2UL );
  check_bytes( "batch2", buf, encode( 1700000000000000000L ), batch2, sizeof(batch2) );
}

static void
test_batch_limits( void ) {
  static uchar big[ FD_TPU_MTU+1UL ];
  for( ulong i=0UL; i<sizeof(big); i++ ) big[ i ] = (uchar)( i^0x5a );

  /* A full batch of max-size transactions with max-length addresses
     fits in FD_PRECNF_BATCH_ENC_MAX. */
  fd_precnf_batch_init( batch );
  for( ulong i=0UL; i<FD_PRECNF_BATCH_TXN_MAX; i++ ) {
    FD_TEST( fd_precnf_batch_append( batch, big, FD_TPU_MTU, ip4( 255, 255, 255, 255 ) ) );
  }
  /* The next one is refused (txn limit) and nothing is added. */
  FD_TEST( !fd_precnf_batch_append( batch, big, FD_TPU_MTU, 0U ) );
  FD_TEST( fd_precnf_batch_txn_cnt( batch )==FD_PRECNF_BATCH_TXN_MAX );
  ulong sz = encode( 1700000000123456789L );
  FD_TEST( sz<=FD_PRECNF_BATCH_ENC_MAX );
  FD_TEST( buf[0]==0x0a ); /* RelayUpdate.batches */

  /* An output buffer that is too small makes encode fail cleanly. */
  FD_TEST( !fd_precnf_batch_encode( batch, 1700000000123456789L, buf, sz-1UL ) );

  /* A transaction larger than FD_TPU_MTU is refused. */
  fd_precnf_batch_init( batch );
  FD_TEST( !fd_precnf_batch_append( batch, big, FD_TPU_MTU+1UL, 0U ) );
  FD_TEST( fd_precnf_batch_txn_cnt( batch )==0UL );
}

static void
test_ip4_formats( void ) {
  /* Every octet width (1, 2 and 3 digits) shows up in Meta.addr. */
  uchar p[ 100 ] = {0};
  struct { uint ip; char const * s; } cases[] = {
    { ip4(   0,  0,  0,  1 ), "0.0.0.1"         },
    { ip4(   9, 10, 99,100 ), "9.10.99.100"     },
    { ip4( 255,255,255,255 ), "255.255.255.255" },
    { ip4( 135,148, 52, 55 ), "135.148.52.55"   },
  };
  for( ulong i=0UL; i<sizeof(cases)/sizeof(cases[0]); i++ ) {
    fd_precnf_batch_init( batch );
    FD_TEST( fd_precnf_batch_append( batch, p, sizeof(p), cases[ i ].ip ) );
    ulong sz = encode( 1L );
    ulong n  = strlen( cases[ i ].s );
    /* Meta.addr is "0x12 <len> <ascii>". */
    uchar needle[ 32 ] = { 0x12, (uchar)n };
    memcpy( needle+2, cases[ i ].s, n );
    int found = 0;
    for( ulong j=0UL; j+n+2UL<=sz; j++ ) if( !memcmp( buf+j, needle, n+2UL ) ) found = 1;
    if( FD_UNLIKELY( !found ) ) FD_LOG_ERR(( "addr %s not found in encoding", cases[ i ].s ));
  }
}

